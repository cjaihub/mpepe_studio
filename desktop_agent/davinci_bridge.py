import sys
import os

def get_resolve():
    """Try to import DaVinci Resolve Scripting API"""
    try:
        import DaVinciResolveScript as dvr_script
        resolve = dvr_script.scriptapp("Resolve")
        return resolve
    except ImportError:
        # In actual usage on Mac, the python module is usually in:
        # /Library/Application Support/Blackmagic Design/DaVinci Resolve/Developer/Scripting/Modules
        sys.path.append("/Library/Application Support/Blackmagic Design/DaVinci Resolve/Developer/Scripting/Modules")
        try:
            import DaVinciResolveScript as dvr_script
            resolve = dvr_script.scriptapp("Resolve")
            return resolve
        except ImportError:
            return None

def is_running():
    """Check if DaVinci Resolve is running and accessible"""
    return get_resolve() is not None

def execute(command, payload):
    """Execute command in DaVinci Resolve"""
    print(f"[DaVinci Bridge] Executing: {command} with {payload}")
    
    resolve = get_resolve()
    if not resolve:
        return False, "DaVinci Resolve is not running or scripting API is inaccessible."
        
    projectManager = resolve.GetProjectManager()
    project = projectManager.GetCurrentProject()
    
    if not project:
        return False, "No active project in DaVinci Resolve."
        
    timeline = project.GetCurrentTimeline()
    if not timeline:
        return False, "No active timeline in DaVinci Resolve."

    if command == "add_marker":
        name = payload.get("name", "AI Marker")
        color = payload.get("color", "Blue")
        note = payload.get("note", "Generated by CJ AI")
        
        frame_id = timeline.GetCurrentTimecode() # Get current frame
        # Convert timecode to frame is complex, assuming current playhead position
        
        # DaVinci AddMarker: frameId, color, name, note, duration, customData
        # (needs actual frame index, for now we just try adding at 0 for demo)
        success = timeline.AddMarker(0, color, name, note, 1, "")
        
        if success:
            return True, f"Marker '{name}' added."
        return False, "Failed to add marker in DaVinci."
        
    elif command == "import_media":
        path = payload.get("path")
        if not path or not os.path.exists(path):
            return False, "Invalid media path."
            
        mediaPool = project.GetMediaPool()
        items = mediaPool.ImportMedia([path])
        
        if items and len(items) > 0:
            return True, "Media imported successfully."
        return False, "Failed to import media."
        
    else:
        return False, f"Unknown DaVinci command: {command}"
