import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:oneova/feed/models/video_transcript_model.dart';
import 'package:oneova/feed/services/oneova_transcription_service.dart';

void main() {
  group('Oneova Video Transcription & Closed Captions Test Suite', () {
    test('CaptionSegment timestampLabel formats minutes and seconds correctly', () {
      const seg1 = CaptionSegment(startMs: 3500, endMs: 6000, text: 'Hello world');
      expect(seg1.timestampLabel, '00:03');

      const seg2 = CaptionSegment(startMs: 65400, endMs: 70000, text: 'One minute in');
      expect(seg2.timestampLabel, '01:05');
    });

    test('VideoTranscript segmentAt resolves active timed line', () {
      final transcript = VideoTranscript(
        contentId: 'reel_123',
        language: 'en',
        segments: const [
          CaptionSegment(startMs: 0, endMs: 2000, text: 'Intro segment'),
          CaptionSegment(startMs: 2200, endMs: 5000, text: 'Welcome to Oneova Studio'),
          CaptionSegment(startMs: 5200, endMs: 9000, text: 'Enjoy high quality streaming'),
        ],
      );

      // In the middle of segment 2
      final active = transcript.segmentAt(3500);
      expect(active, isNotNull);
      expect(active!.text, 'Welcome to Oneova Studio');

      // In the gap between 2 and 3
      final gap = transcript.segmentAt(2100);
      expect(gap, isNull);

      // Past the end
      final past = transcript.segmentAt(10000);
      expect(past, isNull);
    });

    test('OneovaTranscriptionService splits dialogue into natural synchronized phrases', () {
      final service = OneovaTranscriptionService();
      final transcript = service.getTranscript(
        'mock_test_id',
        fallbackText: 'Discover the future of social video. Oneova brings real-time creative tools directly into your hands. Let us get started!',
        duration: const Duration(seconds: 12),
      );

      expect(transcript, completion(isNotNull));
      transcript.then((t) {
        expect(t, isNotNull);
        expect(t!.segments.isNotEmpty, isTrue);
        expect(t.contentId, 'mock_test_id');
        expect(t.isAutoGenerated, isTrue);
      });
    });

    test('OneovaCaptionsEnabledNotifier toggles caption visibility preference', () {
      final container = ProviderContainer();
      addTearDown(container.dispose);

      expect(container.read(oneovaCaptionsEnabledProvider), isTrue);

      container.read(oneovaCaptionsEnabledProvider.notifier).toggle();
      expect(container.read(oneovaCaptionsEnabledProvider), isFalse);

      container.read(oneovaCaptionsEnabledProvider.notifier).toggle();
      expect(container.read(oneovaCaptionsEnabledProvider), isTrue);
    });
  });
}
