#!/usr/bin/env bash
# Deploys ONLY the Live Studio v2 Cloud Functions (ls*) to production.
#
#   bash tools/livekit/deploy_functions.sh [project]
#
# Why a staged copy: the repo's functions/index.ts loads every module, and the
# deploy CLI then requires every secret any of them defines (e.g. GMAIL_*,
# GEMINI_API_KEY). The staged entry point exports only the ls* functions, so
# only LIVEKIT_API_KEY / LIVEKIT_API_SECRET are needed. `--only` never touches
# or deletes other functions.
set -euo pipefail
cd "$(dirname "$0")/../.."
PROJECT="${1:-mpepe-2b4bd}"
STAGE="$(mktemp -d)/ls-deploy"
mkdir -p "$STAGE"
trap 'rm -rf "$(dirname "$STAGE")"' EXIT

rsync -a --exclude node_modules --exclude lib --exclude .ls-build --exclude '*.local' functions/ "$STAGE/functions/"
ln -s "$PWD/functions/node_modules" "$STAGE/functions/node_modules"
cp .firebaserc "$STAGE/"
cat > "$STAGE/firebase.json" <<'EOF'
{
  "functions": [
    {
      "source": "functions",
      "codebase": "default",
      "ignore": ["node_modules", ".git", "firebase-debug.log", "firebase-debug.*.log", "*.local", ".ls-build"],
      "predeploy": ["npm --prefix \"$RESOURCE_DIR\" run build"]
    }
  ]
}
EOF
cat > "$STAGE/functions/src/index.ts" <<'EOF'
// Staged deploy entry for Live Studio v2 only (generated by deploy_functions.sh).
import { setGlobalOptions } from 'firebase-functions/v2';
import * as admin from 'firebase-admin';

setGlobalOptions({
  enforceAppCheck: process.env.APP_CHECK_ENFORCE === 'true',
  memory: '512MiB',
  timeoutSeconds: 60,
});

admin.initializeApp();

export { lsStart, lsToken, lsEnd, lsTime, lsStateFull, lsSetOwnMedia } from './liveStudio/media';
export { lsSetSettings } from './liveStudio/settings';
export { lsHeartbeat, lsSweepOrphanLives } from './liveStudio/lifecycle';
export { lsFun } from './liveStudio/fun';
export { lsGift } from './liveStudio/gifts';
export { lsDestinations, lsBroadcast, lsRecordingDecision } from './liveStudio/broadcast';
export { lsSetLayout } from './liveStudio/layout';
export { lsRequestJoin, lsCancelRequest, lsRespondRequest, lsModerate, lsLeaveStage } from './liveStudio/roles';
export { lsSetTable, lsPlayback } from './liveStudio/table';
export { lsMediaKey, lsSecOnIncident, lsSecOnBlock, lsSecOnMemberWrite } from './liveStudio/security';
export { lsSetChatMode, lsSetJoinRequests } from './liveStudio/controls';
export { lsComment, lsDeleteComment, lsMuteChat, lsReact, lsShare, lsLivekitWebhook, lsGifSearch } from './liveStudio/social';
export { lsWatch, lsYouTubeSearch } from './liveStudio/watch';
export { lsPool } from './liveStudio/pool';
EOF

FNS=lsStart,lsToken,lsEnd,lsTime,lsStateFull,lsSetOwnMedia,lsSetSettings,lsHeartbeat,lsSweepOrphanLives,lsFun,lsGift,lsDestinations,lsBroadcast,lsRecordingDecision,lsSetLayout,lsRequestJoin,lsCancelRequest,lsRespondRequest,lsModerate,lsLeaveStage,lsSetTable,lsPlayback,lsMediaKey,lsSecOnIncident,lsSecOnBlock,lsSecOnMemberWrite,lsSetChatMode,lsSetJoinRequests,lsComment,lsDeleteComment,lsMuteChat,lsReact,lsShare,lsLivekitWebhook,lsGifSearch,lsWatch,lsYouTubeSearch,lsPool
ONLY=$(echo "$FNS" | tr ',' '\n' | sed 's/^/functions:/' | paste -sd, -)
cd "$STAGE"
firebase deploy --only "$ONLY" --project "$PROJECT" --non-interactive
