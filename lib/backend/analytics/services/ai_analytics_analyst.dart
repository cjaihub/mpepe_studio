import 'dart:convert';
import 'package:oneova/backend/analytics/models/analytics_models.dart';
import 'package:oneova/backend/analytics/models/ai_analytics_models.dart';
import 'package:oneova/backend/ai_agents/openrouter_agent_service.dart';

class AIAnalyticsAnalyst {
  final OpenRouterAgentService _agentService;

  AIAnalyticsAnalyst(this._agentService);

  final String _systemPrompt = '''
You are the elite AI Data Analyst for ONEROVA. Your job is to answer the user's question using ONLY the provided Analytics Dashboard Data payload.
You must strictly differentiate between OBSERVED metrics (directly provided by an API), CALCULATED metrics (composite metrics generated by our engine), and your own AI HYPOTHESIS.
You MUST output your analysis as a valid JSON object matching this schema EXACTLY:
{
  "type": "performanceDriver|retentionDropoff|platformComparison|topicTrend|conversionAnalysis|repurposeSuggestion",
  "title": "A short engaging title",
  "hypothesis": "Your analytical conclusion explaining the data.",
  "confidence": "high|medium|low",
  "evidence": [
    {
      "metricName": "Exact name of metric",
      "value": "Value as a string",
      "isCalculated": boolean,
      "calculationNote": "Include this if it was a calculated/composite metric to show your work"
    }
  ]
}
NEVER invent metrics. If the data does not answer the question, state that in the hypothesis and return low confidence with empty evidence.
''';

  Future<AIAnalyticsInsight?> generateInsight(String question, AnalyticsDashboardData dashboardData) async {
    // 1. Serialize the dashboard data into a strict factual representation for the LLM.
    final List<Map<String, dynamic>> contextData = dashboardData.metrics.map((m) {
      final isComposite = m.metadataSources.any((s) => s.calculationNote != null);
      final calcNote = m.metadataSources.map((s) => s.calculationNote).where((n) => n != null).join(' | ');

      return {
        'id': m.id,
        'name': m.name,
        'value': m.value,
        'unit': m.unit,
        'isCalculated': isComposite,
        'calculationNote': isComposite && calcNote.isNotEmpty ? calcNote : null,
        'sources': m.metadataSources.map((s) => s.source.name).toList(),
      };
    }).toList();

    final payload = {
      'question': question,
      'globalCoverage': dashboardData.overallCoverage,
      'metrics': contextData,
      'providerErrors': dashboardData.providerErrors.map((k, v) => MapEntry(k.name, v)),
    };

    final userPrompt = jsonEncode(payload);

    // 2. Query the LLM
    final String? llmResponse = await _agentService.queryAgent(_systemPrompt, userPrompt);
    
    if (llmResponse == null || llmResponse.isEmpty) {
      return null;
    }

    try {
      // 3. Parse and validate the response against the strict model
      // We'll try to find the JSON object if the LLM added markdown formatting
      final String cleanJson = _extractJson(llmResponse);
      final Map<String, dynamic> data = jsonDecode(cleanJson);

      return _parseInsight(data);
    } catch (e) {
      // ignore: avoid_print
      print('AIAnalyticsAnalyst JSON parse error: $e\\nResponse was: $llmResponse');
      return null;
    }
  }

  String _extractJson(String response) {
    final start = response.indexOf('{');
    final end = response.lastIndexOf('}');
    if (start != -1 && end != -1 && end > start) {
      return response.substring(start, end + 1);
    }
    return response;
  }

  AIAnalyticsInsight _parseInsight(Map<String, dynamic> data) {
    InsightType type;
    switch (data['type']) {
      case 'performanceDriver': type = InsightType.performanceDriver; break;
      case 'retentionDropoff': type = InsightType.retentionDropoff; break;
      case 'platformComparison': type = InsightType.platformComparison; break;
      case 'topicTrend': type = InsightType.topicTrend; break;
      case 'conversionAnalysis': type = InsightType.conversionAnalysis; break;
      case 'repurposeSuggestion': type = InsightType.repurposeSuggestion; break;
      default: type = InsightType.performanceDriver;
    }

    InsightConfidence confidence;
    switch (data['confidence']) {
      case 'high': confidence = InsightConfidence.high; break;
      case 'medium': confidence = InsightConfidence.medium; break;
      case 'low': confidence = InsightConfidence.low; break;
      default: confidence = InsightConfidence.low;
    }

    final List<dynamic> evidenceList = data['evidence'] ?? [];
    final parsedEvidence = evidenceList.map((e) => AIAnalyticsEvidence(
      metricName: e['metricName']?.toString() ?? 'Unknown',
      value: e['value']?.toString() ?? '0',
      isCalculated: e['isCalculated'] == true,
      calculationNote: e['calculationNote']?.toString(),
    )).toList();

    return AIAnalyticsInsight(
      id: DateTime.now().millisecondsSinceEpoch.toString(),
      type: type,
      title: data['title'] ?? 'Analytics Insight',
      hypothesis: data['hypothesis'] ?? 'No clear hypothesis could be generated.',
      evidence: parsedEvidence,
      confidence: confidence,
    );
  }
}
