enum InsightConfidence { high, medium, low }

enum InsightType {
  performanceDriver,  // "Why did this video perform well?"
  retentionDropoff,   // "Where did viewers leave?"
  platformComparison, // "Which platform performs best?"
  topicTrend,         // "Which topics are growing?"
  conversionAnalysis, // "Which videos convert followers?"
  repurposeSuggestion // "Which content should be repurposed?"
}

class AIAnalyticsEvidence {
  final String metricName;
  final String value;
  final bool isCalculated; // Differentiates observed vs calculated
  final String? calculationNote; // Used if calculated

  const AIAnalyticsEvidence({
    required this.metricName,
    required this.value,
    required this.isCalculated,
    this.calculationNote,
  });
}

class AIAnalyticsInsight {
  final String id;
  final InsightType type;
  final String title;
  
  /// The specific hypothesis or conclusion generated by the AI
  final String hypothesis;
  
  /// The strict factual evidence backing the hypothesis
  final List<AIAnalyticsEvidence> evidence;
  
  final InsightConfidence confidence;

  const AIAnalyticsInsight({
    required this.id,
    required this.type,
    required this.title,
    required this.hypothesis,
    required this.evidence,
    required this.confidence,
  });

  bool get isSupported => evidence.isNotEmpty;
}
