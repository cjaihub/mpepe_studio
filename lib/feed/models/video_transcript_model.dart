/// Closed captions and video transcription models.
library;

/// A single timed subtitle line / segment.
class CaptionSegment {
  final int startMs;
  final int endMs;
  final String text;

  const CaptionSegment({
    required this.startMs,
    required this.endMs,
    required this.text,
  });

  String get timestampLabel {
    final s = (startMs / 1000).floor();
    final m = (s / 60).floor();
    final remSec = s % 60;
    return '${m.toString().padLeft(2, '0')}:${remSec.toString().padLeft(2, '0')}';
  }

  Map<String, dynamic> toMap() => {
        'startMs': startMs,
        'endMs': endMs,
        'text': text,
      };

  factory CaptionSegment.fromMap(Map<String, dynamic> map) => CaptionSegment(
        startMs: (map['startMs'] as num?)?.toInt() ?? 0,
        endMs: (map['endMs'] as num?)?.toInt() ?? 0,
        text: (map['text'] as String?)?.trim() ?? '',
      );
}

/// Represents the full transcript of a video / reel.
class VideoTranscript {
  final String contentId;
  final String language;
  final List<CaptionSegment> segments;
  final bool isAutoGenerated;

  const VideoTranscript({
    required this.contentId,
    this.language = 'en',
    this.segments = const [],
    this.isAutoGenerated = true,
  });

  String get fullText => segments.map((s) => s.text).join(' ');

  /// Finds the subtitle line active at [positionMs].
  CaptionSegment? segmentAt(int positionMs) {
    if (segments.isEmpty) return null;
    for (final seg in segments) {
      if (positionMs >= seg.startMs && positionMs <= seg.endMs) {
        return seg;
      }
    }
    return null;
  }

  Map<String, dynamic> toMap() => {
        'contentId': contentId,
        'language': language,
        'isAutoGenerated': isAutoGenerated,
        'segments': segments.map((s) => s.toMap()).toList(),
      };

  factory VideoTranscript.fromMap(Map<String, dynamic> map) => VideoTranscript(
        contentId: map['contentId'] as String? ?? '',
        language: map['language'] as String? ?? 'en',
        isAutoGenerated: map['isAutoGenerated'] as bool? ?? true,
        segments: (map['segments'] as List<dynamic>?)
                ?.map((e) => CaptionSegment.fromMap(Map<String, dynamic>.from(e as Map)))
                .toList() ??
            const [],
      );
}
